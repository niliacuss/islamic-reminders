#!/usr/bin/env python3
"""Send an Islamic reminder to Telegram based on the current Europe/Amsterdam time.

Slot windows (tolerant of GitHub Actions cron delays), five reminders per day:
- Hour 10-12  -> slot 0 (10u reminder)
- Hour 13-15  -> slot 1 (13u reminder)
- Hour 16-18  -> slot 2 (16u reminder)
- Hour 19-21  -> slot 3 (19u reminder)
- Hour 22-23  -> slot 4 (22u reminder)
- Hour 0-9    -> skip (pre-morning window)

A state file (.last_sent.json) records the last (date, slot) that was delivered,
so if GitHub Actions fires twice within the same slot window the second run skips
instead of resending.

The message is sent to TELEGRAM_CHAT_ID and, if set, also to TELEGRAM_CHAT_ID_2.
A partial failure (one recipient succeeds, the other fails) is logged but does not
fail the script. The script exits 1 only when all send attempts fail. State is
updated whenever at least one recipient received the message.

FORCE_SEND=1 bypasses both the window check and the state file check, and
deliberately does NOT update the state file (so manual tests do not interfere
with the scheduled rotation).

Dated reminders: if reminders_gedateerd.json contains today's date
({"2026-12-01": [r0, r1, r2, r3, r4], ...}, each r = {"text", "thema"}), the
entry for the active slot is sent as plain text (no parse_mode). Otherwise, or
if that entry is unusable (missing, empty, longer than 4096 characters, or an
unfilled "[... invullen]" placeholder), the rotation from reminders.json is used
as before. The file is generated by scripts/maak_gedateerd.py.

Dry run (prints, sends nothing, never touches the state file):
    python send_reminder.py --dry-run --date 2026-12-01 --slot 0
Without --slot all five slots of the date are printed; without --date, today.
"""
from __future__ import annotations

import argparse
import html
import json
import os
import re
import sys
from datetime import date, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import requests

AMSTERDAM = ZoneInfo("Europe/Amsterdam")
SLOTS_PER_DAY = 5  # 10:00, 13:00, 16:00, 19:00, 22:00
SLOT_TIMES = ("10:00", "13:00", "16:00", "19:00", "22:00")
SCRIPT_DIR = Path(__file__).parent
REMINDERS_PATH = SCRIPT_DIR / "reminders.json"
DATED_PATH = SCRIPT_DIR / "reminders_gedateerd.json"
STATE_PATH = SCRIPT_DIR / ".last_sent.json"
TELEGRAM_API = "https://api.telegram.org/bot{token}/sendMessage"
TELEGRAM_MAX_LEN = 4096
# Same pattern as scripts/maak_gedateerd.py: "[vertaling Siregar invullen]" etc.
PLACEHOLDER_RE = re.compile(
    r"\[[^\]\n]*(?:invullen|todo|nakijken|placeholder)[^\]\n]*\]", re.IGNORECASE
)


def log(msg: str) -> None:
    print(f"[send_reminder] {msg}", flush=True)


def fail(msg: str) -> None:
    log(f"ERROR: {msg}")
    sys.exit(1)


def slot_for_hour(hour: int) -> int | None:
    """Return the active slot for an Amsterdam hour, or None if outside the window."""
    if 10 <= hour <= 12:
        return 0
    if 13 <= hour <= 15:
        return 1
    if 16 <= hour <= 18:
        return 2
    if 19 <= hour <= 21:
        return 3
    if 22 <= hour <= 23:
        return 4
    return None


def load_state() -> dict:
    if not STATE_PATH.exists():
        return {}
    try:
        return json.loads(STATE_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        log(f"Warning: could not read {STATE_PATH.name} ({e}); treating as empty.")
        return {}


def save_state(today_iso: str, slot: int) -> None:
    payload = {"date": today_iso, "slot": slot}
    STATE_PATH.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    log(f"State file updated: date={today_iso} slot={slot}")


def send_to_chat(
    token: str, chat_id: str, text: str, parse_mode: str | None = "HTML"
) -> tuple[bool, str | None]:
    """Send text to a single Telegram chat. Returns (success, error_message).

    parse_mode=None sends plain text: Telegram shows every character literally.
    """
    payload = {
        "chat_id": chat_id,
        "text": text,
        "disable_web_page_preview": True,
    }
    if parse_mode:
        payload["parse_mode"] = parse_mode
    try:
        resp = requests.post(
            TELEGRAM_API.format(token=token),
            json=payload,
            timeout=30,
        )
    except requests.RequestException as e:
        return False, f"request error: {e}"

    if resp.status_code != 200:
        return False, f"HTTP {resp.status_code}: {resp.text}"
    return True, None


def telegram_length(text: str) -> int:
    """Length as Telegram counts it (UTF-16 code units, so most emoji count as 2)."""
    return len(text.encode("utf-16-le")) // 2


def rotation_message(day: date, slot_index: int) -> str:
    """Pick the rotating reminder from reminders.json (HTML, title in bold)."""
    try:
        reminders = json.loads(REMINDERS_PATH.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"reminders.json not found at {REMINDERS_PATH}")
    except json.JSONDecodeError as e:
        fail(f"reminders.json is not valid JSON: {e}")

    if not isinstance(reminders, list):
        fail("reminders.json must contain a JSON array.")
    if not reminders:
        fail("reminders.json is empty — add reminder objects before scheduling runs.")

    days_since_epoch = (day - date(1970, 1, 1)).days
    index = ((days_since_epoch * SLOTS_PER_DAY) + slot_index) % len(reminders)
    reminder = reminders[index]

    if not isinstance(reminder, dict):
        fail(f"Reminder at index {index} is not an object: {reminder!r}")

    title = (reminder.get("title") or "").strip()
    body = (reminder.get("body") or "").strip()
    if not title or not body:
        fail(f"Reminder at index {index} is missing title or body: {reminder!r}")

    text = f"<b>{html.escape(title)}</b>\n\n{html.escape(body)}"
    log(
        f"Selected reminder index {index} "
        f"(slot {slot_index}, day {days_since_epoch}, total {len(reminders)})."
    )
    return text


def dated_message(day: date, slot_index: int) -> str | None:
    """Return the dated reminder for (day, slot) from reminders_gedateerd.json.

    Returns None when the date is not in the file. Any problem with the file or
    the entry is logged as a warning and also returns None, so the caller falls
    back to the rotation and a reminder still goes out.
    """
    if not DATED_PATH.exists():
        return None
    try:
        dated = json.loads(DATED_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        log(f"WARNING: could not read {DATED_PATH.name} ({e}); using rotation.")
        return None
    if not isinstance(dated, dict):
        log(f"WARNING: {DATED_PATH.name} must contain a JSON object; using rotation.")
        return None

    key = day.isoformat()
    if key not in dated:
        return None
    where = f"{DATED_PATH.name} {key} slot {slot_index}"
    entries = dated[key]
    if not isinstance(entries, list) or slot_index >= len(entries):
        log(f"WARNING: {where} is missing; using rotation.")
        return None
    entry = entries[slot_index]
    text = entry.get("text") if isinstance(entry, dict) else None
    if not isinstance(text, str) or not text.strip():
        log(f"WARNING: {where} has no text; using rotation.")
        return None
    text = text.strip()
    length = telegram_length(text)
    if length > TELEGRAM_MAX_LEN:
        log(
            f"WARNING: {where} is {length} characters "
            f"(Telegram max {TELEGRAM_MAX_LEN}); using rotation."
        )
        return None
    if PLACEHOLDER_RE.search(text):
        log(f"WARNING: {where} contains an unfilled placeholder; using rotation.")
        return None

    log(f"Selected dated reminder {key} slot {slot_index} ({length} characters).")
    return text


def select_message(day: date, slot_index: int) -> tuple[str, str | None, str]:
    """Return (text, parse_mode, source) for a day and slot.

    A dated reminder wins and is sent as plain text (parse_mode None), so *, _,
    [, <, Arabic and emoji arrive exactly as written. Otherwise the rotation from
    reminders.json is used with HTML, as before.
    """
    text = dated_message(day, slot_index)
    if text is not None:
        return text, None, DATED_PATH.name
    log(f"No usable dated reminder for {day.isoformat()}; using rotation.")
    return rotation_message(day, slot_index), "HTML", REMINDERS_PATH.name


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Send the Islamic reminder for the current slot to Telegram."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the message(s) instead of sending. No Telegram, no state file.",
    )
    parser.add_argument(
        "--date",
        type=date.fromisoformat,
        help="Date YYYY-MM-DD (only with --dry-run). Default: today in Amsterdam.",
    )
    parser.add_argument(
        "--slot",
        type=int,
        choices=range(SLOTS_PER_DAY),
        help="Slot 0-4 = 10, 13, 16, 19, 22 uur (only with --dry-run). Default: all.",
    )
    args = parser.parse_args(argv)
    if (args.date is not None or args.slot is not None) and not args.dry_run:
        parser.error("--date and --slot can only be used together with --dry-run.")
    return args


def dry_run(day: date | None, slot: int | None) -> None:
    """Print what would be sent for a day (and slot). Sends nothing, writes nothing."""
    day = day or datetime.now(AMSTERDAM).date()
    slots = [slot] if slot is not None else list(range(SLOTS_PER_DAY))
    log(f"DRY RUN: nothing is sent and {STATE_PATH.name} is not touched.")
    for s in slots:
        text, parse_mode, source = select_message(day, s)
        print(
            f"\n===== {day.isoformat()} slot {s} ({SLOT_TIMES[s]}) | source: {source}"
            f" | parse_mode: {parse_mode or 'none (plain text)'}"
            f" | {telegram_length(text)}/{TELEGRAM_MAX_LEN} characters ====="
        )
        print(text)
        print("===== end =====")


def main(argv: list[str] | None = None) -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # Arabic and emoji on Windows
    args = parse_args(argv)
    if args.dry_run:
        dry_run(args.date, args.slot)
        return

    now = datetime.now(AMSTERDAM)
    log(f"Amsterdam local time: {now.isoformat()}")

    force = os.environ.get("FORCE_SEND") == "1"

    slot_index = slot_for_hour(now.hour)
    if slot_index is None:
        if force:
            slot_index = 0
            log(
                f"FORCE_SEND=1 — hour {now.hour} is outside the active window "
                "(10-23); defaulting to slot 0."
            )
        else:
            log(
                f"Hour {now.hour} is outside the active window (10-23). "
                "Exiting cleanly."
            )
            return

    today_iso = now.date().isoformat()

    if force:
        log("FORCE_SEND=1 — skipping state file check, will not update state.")
    else:
        state = load_state()
        if state.get("date") == today_iso and state.get("slot") == slot_index:
            log(
                f"Slot {slot_index} for {today_iso} was already sent "
                f"(per {STATE_PATH.name}). Exiting cleanly."
            )
            return

    text, parse_mode, _ = select_message(now.date(), slot_index)

    token = os.environ.get("TELEGRAM_BOT_TOKEN", "").strip()
    if not token:
        fail("TELEGRAM_BOT_TOKEN environment variable is not set.")

    primary = os.environ.get("TELEGRAM_CHAT_ID", "").strip()
    if not primary:
        fail("TELEGRAM_CHAT_ID environment variable is not set.")

    recipients = [("primary", primary)]
    secondary = os.environ.get("TELEGRAM_CHAT_ID_2", "").strip()
    if secondary:
        recipients.append(("secondary", secondary))

    log(f"Sending to {len(recipients)} recipient(s).")

    successes = 0
    for label, chat_id in recipients:
        ok, err = send_to_chat(token, chat_id, text, parse_mode)
        if ok:
            log(f"Sent to {label}.")
            successes += 1
        else:
            log(f"WARNING: send to {label} failed — {err}")

    if successes == 0:
        fail(f"All {len(recipients)} send attempt(s) failed.")

    log(f"Delivered to {successes}/{len(recipients)} recipient(s).")

    if not force:
        save_state(today_iso, slot_index)


if __name__ == "__main__":
    main()
